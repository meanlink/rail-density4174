import hashlib, json
def checksum(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False).encode()).hexdigest()
def dataset_dict(d):
    return {'id':d.id, 'name':d.name, 'source':d.source, 'rows':len(d.records), 'checksum':d.checksum, 'created_at':d.created_at, 'updated_at':d.updated_at}
def supplement_dict(s):
    return {'id':s.id,'dataset_id':s.dataset_id,'kind':s.kind,'source':s.source,'checksum':s.checksum,'received':s.received,'added':s.added,'corrected':s.corrected,'revoked':s.revoked,'ignored':s.ignored,'actor':s.actor,'created_at':s.created_at}
def job_dict(j):
    return {k:getattr(j,k) for k in ['id','name','dataset_id','params','status','result','error','approved','created_at','finished_at']}
def report_dict(r):
    return {k:getattr(r,k) for k in ['id','name','job_id','destination','interval_seconds','next_run','enabled']}
def delivery_dict(d):
    return {k:getattr(d,k) for k in ['id','report_id','created_at','checksum','filename','destination']}
